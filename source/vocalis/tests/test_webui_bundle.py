"""The committed webui bundle must match its source modules so deployments run the code checked by the test suite."""
from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from conftest import REPO_ROOT  # noqa: F401  (sys.path side effect)

BUNDLE = Path(REPO_ROOT) / "src" / "webui" / "bundle" / "app.js"
JSDIR = Path(REPO_ROOT) / "src" / "webui" / "js"
BUILDER = Path(REPO_ROOT) / "tools" / "build_webui.mjs"
ESBUILD = Path(REPO_ROOT) / "node_modules" / "esbuild"


def _modules() -> list[str]:
    return sorted(p.relative_to(JSDIR).as_posix() for p in JSDIR.rglob("*.js"))


def test_the_bundle_exists_and_is_the_thing_the_page_loads():
    """No node required — this half runs anywhere, including a box that never ran `npm install`."""
    assert BUNDLE.is_file(), (
        f"{BUNDLE.relative_to(REPO_ROOT)} is missing and index.html loads it, so the UI is a blank "
        "page. Run: npm run build")
    text = BUNDLE.read_text(encoding="utf-8")
    assert len(text) > 100_000, f"the bundle is {len(text)} bytes, which cannot be the retained UI graph"
    assert "GENERATED by tools/build_webui.mjs" in text[:400], (
        "the bundle has lost its generated-file banner, which is the only warning a human editing "
        "it would get before the next build silently discarded their work")
    page = (Path(REPO_ROOT) / "src" / "webui" / "index.html").read_text(encoding="utf-8")
    assert '<script type="module" src="/webui/bundle/app.js">' in page, (
        "index.html no longer loads the bundle — if that was deliberate the request count went "
        "back from 1 to 65, and if it was not, the page is running stale code")


def test_every_module_is_in_the_bundles_published_registry():
    """🔴 THE REGISTRY IS WHAT KEEPS THE BROWSER SPECS POINTED AT THE REAL APP.

    `_websrc.mjs`'s PUBLISH_SPEC_SURFACE reaches the page's instances through
    `window.__VOCALIS__[specifier]`. A module missing from it falls back to importing the source
    URL, which under a bundled page builds a SECOND copy with its own state, wired to nothing —
    and the spec then asserts against a private replica and fails as wrong values rather than as
    an error. Checked here on the artifact, because the fallback means nothing throws.
    """
    text = BUNDLE.read_text(encoding="utf-8")
    missing = [m for m in _modules() if json.dumps(m) not in text]
    assert not missing, (
        f"{len(missing)} module(s) are not in the bundle's __VOCALIS__ registry, so a spec "
        f"reaching for them would silently drive a detached copy: {missing[:8]}")


@pytest.mark.skipif(not ESBUILD.is_dir() or shutil.which("node") is None,
                    reason="needs `npm install` (esbuild) and node — the check above covers boxes "
                           "that have neither")
def test_the_committed_bundle_matches_the_sources():
    """The real guard: rebuild and compare. Byte-identical, or the artifact is stale.

    ⚠️ This is why the build is deterministic — no timestamp, no absolute path, no minifier seed
    in the output. A build that differed run-to-run would make this test fail for everyone who
    did not just run it, and the fix would be to delete the test.
    """
    r = subprocess.run(["node", str(BUILDER), "--check"], capture_output=True, text=True,
                       cwd=REPO_ROOT, timeout=180)
    assert r.returncode == 0, (
        "src/webui/bundle/app.js does not match src/webui/js/. The browser is running code that "
        "is not what this repo says it is. Run `npm run build` and commit the result.\n"
        f"{r.stdout}\n{r.stderr}")


# ── the order guard ─────────────────────────────────────────────────────────────────────────
_IMPORT_RE = re.compile(r"""^\s*(?:import|export)\s+[^;]*?from\s+['"]([^'"]+)['"]""", re.M)
_BARE_RE = re.compile(r"""^\s*import\s+['"]([^'"]+)['"]""", re.M)
_MARKER_RE = re.compile(r"^\s*// (src/webui/js/[^\s]+\.js)$", re.M)


def _imports_of(spec: str) -> list[str]:
    """The relative specifiers `spec` imports, in source order, deduped."""
    src = (JSDIR / spec).read_text(encoding="utf-8")
    out: list[str] = []
    for rel in _IMPORT_RE.findall(src) + _BARE_RE.findall(src):
        if not rel.startswith("."):
            continue
        # Normalized textually, NOT through Path.resolve() — resolve() touches the filesystem and
        # would follow a symlink out of the tree, and this has to answer the same thing the BROWSER
        # would compute from the specifier alone.
        parts: list[str] = []
        for seg in (Path(spec).parent / rel).as_posix().split("/"):
            if seg == "..":
                if parts:
                    parts.pop()
            elif seg not in ("", "."):
                parts.append(seg)
        t = "/".join(parts)
        if t not in out:
            out.append(t)
    return out


def _browser_order() -> list[str]:
    """Depth-first POST-order from main.js: a module runs after everything it imports."""
    order: list[str] = []
    seen: set[str] = set()

    def visit(spec: str) -> None:
        if spec in seen:
            return
        seen.add(spec)                      # marked BEFORE recursing -- that is how a cycle is cut
        for d in _imports_of(spec):
            if (JSDIR / d).is_file():
                visit(d)
        order.append(spec)

    visit("main.js")
    return order


def _is_inert_leaf(spec: str) -> bool:
    """A module that imports NOTHING and exports NOTHING.

    🔴 ITS EVALUATION POSITION IS NOT OBSERVABLE, AND A BUNDLER WILL NOT PRESERVE IT. With no
    imports there is nothing it can be waiting for, and with no exports there is nothing that can
    be waiting for it — so esbuild has no edge pinning it and emits it first, while the browser
    reaches it wherever its bare `import './x.js'` happens to sit in main.js. Both are correct and
    they will not agree, so comparing it says nothing about the graph.

    ⚠️ THIS CANNOT MASK A CYCLE, WHICH IS THE ONLY REASON IT IS SAFE TO SKIP. A module in a cycle
    has, by definition, at least one import; the test below still compares every module that has
    a single edge in either direction. `ui/filesafe.js` (7.5.25) is the first module in the tree
    of this shape — one document-level capture listener, no imports, no exports — and adding it
    turned this guard red with no cycle anywhere.
    """
    src = (JSDIR / spec).read_text(encoding="utf-8")
    return not _imports_of(spec) and not re.search(r"^\s*export\s", src, re.M)


def test_the_bundle_evaluates_modules_in_the_browsers_order():
    """🔴 THE GUARD ON THE WHOLE 7.5.6 CYCLE REFACTOR, AND IT FAILS SILENTLY WITHOUT ONE.

    Nearly every module under js/ wires its DOM at module-eval, so the ORDER they run in is part of
    the behavior. The browser evaluates depth-first post-order; a bundler must linearize the same
    graph and always emits a dependency before its dependent. Those two agree on an ACYCLIC graph
    and are free to disagree on a cyclic one -- measured at 7.5.6 before the cut, 62 of 65 modules
    ran at a different position in the bundle than in the browser.

    ⚠️ SO THIS IS REALLY A CYCLE DETECTOR WEARING A MORE USEFUL SHAPE. It does not just say "there
    is a cycle"; it says the artifact the browser will run evaluates in a different order than the
    sources do, which is the thing that actually breaks. Re-introduce a cycle anywhere under js/ and
    this goes red -- and the six leaf modules that exist to prevent that (ui/tabswitch.js,
    pg/pgstate.js's hooks, st/tabstate.js's dispatcher, voices/vcstate.js, voice/vtbus.js) have no
    other test that would notice them being undone.

    📌 `bundle-entry.js` is esbuild's name for the synthetic stdin entry tools/build_webui.mjs
    feeds it. It is not a module on disk and is excluded.
    """
    inert = {s for s in _browser_order() if _is_inert_leaf(s)}
    want = [s for s in _browser_order() if s not in inert]
    text = BUNDLE.read_text(encoding="utf-8")
    got: list[str] = []
    for p in _MARKER_RE.findall(text):
        spec = p[len("src/webui/js/"):]
        if spec != "bundle-entry.js" and spec not in got and spec not in inert:
            got.append(spec)

    assert got == want, (
        "the bundle evaluates modules in a different order than the browser would.\n"
        "That means src/webui/js has an import CYCLE again: inside one, the browser cuts where it "
        "first entered and esbuild cuts dependency-first, and they stop agreeing. Modules here wire "
        "DOM at module-eval, so one will paint into an element another has not created yet -- "
        "intermittently, and only in the built page.\n"
        f"  first divergence at position {next((i for i, (a, b) in enumerate(zip(want, got)) if a != b), len(want))}\n"
        f"  browser: {want[:6]}\n"
        f"  bundle : {got[:6]}\n"
        "Find the cycle with a strongly-connected-component pass over the imports, then break it the "
        "way 7.5.6 did: the function usually cannot move (it touches its module's internals) but the "
        "SUBSCRIPTION can, into a leaf that imports nothing.")
