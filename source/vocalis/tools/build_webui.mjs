/* Bundle the web UI modules into one committed asset to reduce browser requests.
 *
 * Keep src/webui/js unchanged: tests and the source inventory use those modules directly. The
 * bundle drops comments and keeps readable identifiers; `--check` verifies the committed artifact
 * matches the current sources.
 *
 * Module evaluation order must match the browser's depth-first dependency order because modules
 * wire DOM elements at evaluation time. `browserOrder()` constructs that order, and the bundle
 * publishes every module namespace under its source specifier so tests resolve the same modules.
 */
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const JSDIR = join(ROOT, 'src', 'webui', 'js');
const OUTDIR = join(ROOT, 'src', 'webui', 'bundle');
const OUT = join(OUTDIR, 'app.js');
const CHECK = process.argv.includes('--check');

/** Every module under js/, as a POSIX specifier relative to js/ — the same shape the specs use. */
function allModules() {
  const out = [];
  (function walk(dir) {
    for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
      const p = join(dir, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith('.js')) out.push(relative(JSDIR, p).split('\\').join('/'));
    }
  })(JSDIR);
  return out;
}

/** The relative specifiers `spec` imports, in source order. */
function importsOf(spec) {
  const src = readFileSync(join(JSDIR, spec), 'utf8');
  const found = [
    ...src.matchAll(/^\s*(?:import|export)\s+[^;]*?from\s+['"]([^'"]+)['"]/gm),
    ...src.matchAll(/^\s*import\s+['"]([^'"]+)['"]/gm),
  ]
    .map(m => m[1])
    .filter(r => r.startsWith('.'));
  const out = [];
  for (const r of found) {
    const t = join(dirname(spec), r).split('\\').join('/');
    if (!out.includes(t)) out.push(t);
  }
  return out;
}

/* Preserve browser depth-first post-order. Modules wire DOM elements during evaluation, and import
 * cycles can otherwise make the bundler choose a different order. The bundle test independently
 * re-derives this order, so do not replace it with a directory walk.
 */
function browserOrder() {
  const order = [],
    seen = new Set();
  (function visit(spec) {
    if (seen.has(spec)) return;
    seen.add(spec); // marked BEFORE recursing — that is how a cycle is cut
    for (const d of importsOf(spec)) if (existsSync(join(JSDIR, d))) visit(d);
    order.push(spec);
  })('main.js');
  return order;
}

const mods = allModules();
const evalOrder = browserOrder();
const unreachable = mods.filter(m => !evalOrder.includes(m));
if (unreachable.length) {
  console.error(`unreachable from main.js, so the page would never run them: ${unreachable.join(', ')}`);
  process.exit(1);
}

// `./main.js` FIRST so the graph evaluates in exactly the order it does today — the namespace
// imports below then bind already-evaluated modules rather than driving the order themselves.
// ⚠️ Every module here is imported for its SIDE EFFECTS as much as its exports (main.js's header
// says so at length: about a dozen export nothing at all and wire their own controls at
// module-eval), so dropping one produces a dead panel, not a ReferenceError.
// Bare imports FIRST, in the browser's evaluation order — that list ends with main.js, which is
// the graph's root and therefore its own last entry, so the boot IIFE still runs last exactly as
// it does today. The namespace imports after it bind already-evaluated modules and cannot move
// anything; they exist only to build the registry.
const entry = [
  ...evalOrder.map(m => `import './${m}';`),
  ...mods.map((m, i) => `import * as _m${i} from './${m}';`),
  `window.__VOCALIS__ = {`,
  ...mods.map((m, i) => `  ${JSON.stringify(m)}: _m${i},`),
  `};`,
].join('\n');

const result = await build({
  stdin: { contents: entry, resolveDir: JSDIR, sourcefile: 'bundle-entry.js', loader: 'js' },
  bundle: true,
  format: 'iife',
  target: 'es2022',
  platform: 'browser',
  charset: 'utf8',
  legalComments: 'inline',
  minify: false,
  write: false,
  logLevel: 'warning',
});

const built = result.outputFiles[0].text;
const banner =
  `/* GENERATED by tools/build_webui.mjs — DO NOT EDIT, DO NOT PATCH A BUG HERE.\n` +
  `   Sources are src/webui/js/*.js (${mods.length} modules); rebuild with \`npm run build\`.\n` +
  `   An edit here is invisible to every test in tests/ and is overwritten by the next build. */\n`;
const text = banner + built;
const sum = createHash('sha256').update(text, 'utf8').digest('hex').slice(0, 12);

if (CHECK) {
  if (!existsSync(OUT)) {
    console.error(`MISSING: ${relative(ROOT, OUT)} has never been built. Run: npm run build`);
    process.exit(1);
  }
  // Normalize line endings so the check compares artifact content rather than checkout policy.
  const eol = /** @param {string} s */ s => s.replace(/\r\n/g, '\n');
  const have = readFileSync(OUT, 'utf8');
  if (eol(have) !== eol(text)) {
    console.error(`STALE: ${relative(ROOT, OUT)} does not match src/webui/js/. Run: npm run build`);
    process.exit(1);
  }
  console.log(`ok  ${relative(ROOT, OUT)} is current (${mods.length} modules, sha ${sum})`);
} else {
  mkdirSync(OUTDIR, { recursive: true });
  writeFileSync(OUT, text, 'utf8');
  const raw = mods.reduce((n, m) => n + statSync(join(JSDIR, m)).size, 0);
  console.log(
    `built ${relative(ROOT, OUT)}  ${mods.length} modules  ` +
      `${raw.toLocaleString()} -> ${Buffer.byteLength(text).toLocaleString()} bytes  sha ${sum}`,
  );
}
